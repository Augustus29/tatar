//! Sistem panosuna yerel erişim: değişiklik sayacı ve GİZLİ içerik tespiti.
//!
//! Güvenlik kuralı (CLAUDE.md §4.4): şifre yöneticilerinin işaretlediği içerik asla gönderilmez
//! ve geçmişe metin olarak yazılmaz. Metin okuma/yazma `arboard` ile yapılır.

/// Pano içeriği değiştikçe artan sayaç. Okumadan değişimi anlamak için (boştayken CPU ≈ 0).
pub fn change_token() -> i64 {
    imp::change_token()
}

/// Panodaki içerik gizli/geçici olarak işaretlenmiş mi?
pub fn is_concealed() -> bool {
    imp::is_concealed()
}

/// macOS'ta (nspasteboard.org) gizli sayılan tür adları.
#[cfg_attr(not(target_os = "macos"), allow(dead_code))]
pub const MAC_CONCEALED_TYPES: [&str; 3] = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

/// Verilen tür listesinde gizlilik işareti var mı? (saf işlev, test edilebilir)
#[cfg_attr(not(target_os = "macos"), allow(dead_code))]
pub fn mac_types_concealed<S: AsRef<str>>(types: &[S]) -> bool {
    types
        .iter()
        .any(|t| MAC_CONCEALED_TYPES.contains(&t.as_ref()))
}

/// Windows'ta "0" DWORD değeri taşıyan biçimler gizli sayılır
/// (`CanIncludeInClipboardHistory`, `CanUploadToCloudClipboard`).
#[cfg_attr(not(target_os = "windows"), allow(dead_code))]
pub fn windows_dword_hides(value: u32) -> bool {
    value == 0
}

#[cfg(target_os = "macos")]
mod imp {
    use objc2_app_kit::NSPasteboard;

    pub fn change_token() -> i64 {
        NSPasteboard::generalPasteboard().changeCount() as i64
    }

    pub fn is_concealed() -> bool {
        let pb = NSPasteboard::generalPasteboard();
        let Some(types) = pb.types() else {
            return false;
        };
        let names: Vec<String> = types.iter().map(|t| t.to_string()).collect();
        super::mac_types_concealed(&names)
    }
}

#[cfg(target_os = "windows")]
mod imp {
    use windows::Win32::Foundation::HGLOBAL;
    use windows::Win32::System::DataExchange::{
        CloseClipboard, GetClipboardData, GetClipboardSequenceNumber, IsClipboardFormatAvailable,
        OpenClipboard, RegisterClipboardFormatW,
    };
    use windows::Win32::System::Memory::{GlobalLock, GlobalSize, GlobalUnlock};
    use windows::core::w;

    pub fn change_token() -> i64 {
        // SAFETY: parametresiz, yan etkisiz sistem çağrısı.
        i64::from(unsafe { GetClipboardSequenceNumber() })
    }

    /// Pano açıkken açık kalmasın diye kapanışı garantiler.
    struct OpenGuard;
    impl Drop for OpenGuard {
        fn drop(&mut self) {
            // SAFETY: yalnızca OpenClipboard başarılıysa oluşturulur.
            let _ = unsafe { CloseClipboard() };
        }
    }

    fn open() -> Option<OpenGuard> {
        // Pano başka süreçte açıkken kısa süre yeniden dene.
        for _ in 0..5 {
            // SAFETY: pencere kimliği olmadan açmak geçerlidir.
            if unsafe { OpenClipboard(None) }.is_ok() {
                return Some(OpenGuard);
            }
            std::thread::sleep(std::time::Duration::from_millis(10));
        }
        None
    }

    /// Panodaki DWORD değerini okur (pano açık olmalı).
    fn read_dword(format: u32) -> Option<u32> {
        // SAFETY: pano açıkken çağrılıyor; dönen bellek sahibi panodur, kilitleyip kopyalıyoruz.
        unsafe {
            let handle = GetClipboardData(format).ok()?;
            let hglobal = HGLOBAL(handle.0);
            if GlobalSize(hglobal) < 4 {
                return None;
            }
            let ptr = GlobalLock(hglobal) as *const u32;
            if ptr.is_null() {
                return None;
            }
            let v = ptr.read_unaligned();
            let _ = GlobalUnlock(hglobal);
            Some(v)
        }
    }

    pub fn is_concealed() -> bool {
        // SAFETY: kayıt çağrıları sabit geniş dizelerle yapılır.
        let exclude =
            unsafe { RegisterClipboardFormatW(w!("ExcludeClipboardContentFromMonitorProcessing")) };
        let history = unsafe { RegisterClipboardFormatW(w!("CanIncludeInClipboardHistory")) };
        let cloud = unsafe { RegisterClipboardFormatW(w!("CanUploadToCloudClipboard")) };

        // SAFETY: biçim varlığı sorgusu pano açmadan da çalışır.
        if exclude != 0 && unsafe { IsClipboardFormatAvailable(exclude) }.is_ok() {
            return true;
        }
        // Okuyamıyorsak (pano meşgul) güvenli tarafta kalıp gizli say.
        let Some(_guard) = open() else {
            return true;
        };
        [history, cloud].into_iter().any(|f| {
            f != 0
                && unsafe { IsClipboardFormatAvailable(f) }.is_ok()
                && read_dword(f).is_some_and(super::windows_dword_hides)
        })
    }
}

#[cfg(not(any(target_os = "macos", target_os = "windows")))]
mod imp {
    pub fn change_token() -> i64 {
        // Sayaç yok: her çağrıda farklı değer verip okumaya düşeriz (Linux hedef değil).
        use std::sync::atomic::{AtomicI64, Ordering};
        static N: AtomicI64 = AtomicI64::new(0);
        N.fetch_add(1, Ordering::Relaxed)
    }
    pub fn is_concealed() -> bool {
        false
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mac_concealed_types_detected() {
        assert!(mac_types_concealed(&[
            "public.utf8-plain-text",
            "org.nspasteboard.ConcealedType"
        ]));
        assert!(mac_types_concealed(&["org.nspasteboard.TransientType"]));
        assert!(mac_types_concealed(&["org.nspasteboard.AutoGeneratedType"]));
        assert!(!mac_types_concealed(&["public.utf8-plain-text"]));
        assert!(!mac_types_concealed::<&str>(&[]));
    }

    #[test]
    fn windows_dword_zero_hides() {
        assert!(windows_dword_hides(0));
        assert!(!windows_dword_hides(1));
    }
}
